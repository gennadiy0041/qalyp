// Повторное вырезание контактных данных из введения и заключения перед отправкой в ИИ.
// Клиент уже вырезает их сам; сервер делает это ещё раз на случай старого клиента или ошибки.
// Применяется только к введению и заключению: список источников и методичку не трогаем
// (там фамилии авторов и номера — открытые сведения, а лишняя замена сломает сверку).

export const HIDDEN = "[скрыто]";

// e-mail: буквы любого алфавита, цифры, точки, плюс, дефис до и после @
const EMAIL = /[\p{L}\p{N}._%+-]+@[\p{L}\p{N}-]+(?:\.[\p{L}\p{N}-]+)*\.\p{L}{2,}/gu;
// Телефоны Казахстана: +7 или 8, код 7xx / 7xxx (можно в скобках), всего 11 цифр:
// +7 (701) 123-45-67, +77011234567, 8 702 765 43 21, 8(7172)12-34-56.
// Суммы с разрядами вида «87 000 000 000» не трогаем: после 8 код должен идти слитно (7xx).
const SEP = "[\\s\\-.]*";
const PHONE = new RegExp(`(?<![\\d+])(?:\\+\\s?7|8)${SEP}(?:\\(\\s*7\\d{2,3}\\s*\\)|7\\d{2,3})${SEP}\\d(?:${SEP}\\d){5,6}(?!\\d)`, "g");
const phone = (m) => (m.replace(/\D/g, "").length === 11 ? HIDDEN : m);
// ИИН/БИН с подписью: «ИИН 990101 300 123», «БИН: 0405-4000-1234» — 12 цифр с разделителями.
const IIN_LABELED = /((?:ИИН|БИН|ЖСН|IIN|BIN)\s*[:№#-]?\s*)\d(?:[\s-]?\d){11}(?!\d)/giu;
// Любые 12 цифр подряд — так выглядит ИИН или БИН.
const DIGITS12 = /(?<!\d)\d{12}(?!\d)/g;

export function redact(text) {
  return String(text ?? "")
    .replace(EMAIL, HIDDEN)
    .replace(PHONE, phone)
    .replace(IIN_LABELED, (_, label) => label + HIDDEN)
    .replace(DIGITS12, HIDDEN);
}

// Сколько замен сделано (для журнала: только число, без самих данных).
export function countRedactions(before, after) {
  const n = (s) => String(s).split(HIDDEN).length - 1;
  return Math.max(0, n(after) - n(before));
}

export function describeParam(key, def) {
  let type;
  if (def.t === "number") type = `число${def.int ? ", целое" : ""}, от ${def.min} до ${def.max}`;
  else if (def.t === "enum") type = "одно из: " + def.of.map(showValue).join(" | ");
  else if (def.t === "list") type = "список кодов из: " + def.of.map(showValue).join(", ");
  else if (def.t === "bool") type = "true | false";
  else type = "строка";
  const extra = [];
  if (def.alt) extra.push("если разрешено несколько вариантов — первый в value, остальные в alt");
  if (def.rangeMin || def.rangeMax) extra.push("если задана граница или диапазон — min и/или max, value = null");
  return `${key} — ${def.label || key}; ${type}${extra.length ? "; " + extra.join("; ") : ""}`;
}

// Список параметров для промпта собирается из shared/code-params.json, руками не дублируется.
export function paramsForPrompt(params = CODE_PARAMS) {
  return Object.entries(params).map(([k, d]) => describeParam(k, d)).join("\n");
}


// Одноразовая метка для тегов с данными. Своя на каждый вызов: угадать закрывающий тег заранее нельзя.
export function makeNonce() {
  return crypto.randomBytes(6).toString("hex");
}

export function wrap(tag, nonce, text) {
  const clean = String(text ?? "").split(nonce).join("");
  return `<${tag}_${nonce}>\n${clean}\n</${tag}_${nonce}>`;
}

